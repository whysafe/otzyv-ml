def _agree(phrase: str, rng: random.Random) -> str:
    """Раскрывает «(а)» в один из вариантов, чтобы тексты не были шаблонными."""
    while "(а)" in phrase:
        phrase = phrase.replace("(а)", "а" if rng.random() < 0.5 else "", 1)
    return phrase


def _review(rng: random.Random, positive: bool) -> str:
    dom = rng.choice(DOMAINS)
    aspects = rng.sample(dom["aspects"], k=rng.randint(1, 3))
    tmpl = POS_ASPECT if positive else NEG_ASPECT
    parts = [rng.choice(POS_OPEN if positive else NEG_OPEN), rng.choice(dom["intro"]) + "."]
    body = [_agree(rng.choice(tmpl).format(a=a), rng) for a in aspects]
    # Иногда добавляем «смягчающую» оговорку противоположного тона.
    if rng.random() < 0.25:
        other = NEG_ASPECT if positive else POS_ASPECT
        extra = [a for a in dom["aspects"] if a not in aspects][0]
        body.append("хотя " + _agree(rng.choice(other).format(a=extra), rng))
    parts.append(", ".join(body).capitalize() + ".")
    parts.append(rng.choice(POS_CLOSE if positive else NEG_CLOSE))
    if rng.random() < 0.3:
        rng.shuffle(parts)
    text = " ".join(p for p in parts if p)
    return text.lower() if rng.random() < 0.15 else text


def _spam(rng: random.Random) -> str:
    slug = "".join(rng.choice("abcdefghkmnprstxyz0123456789") for _ in range(rng.randint(4, 7)))
    url = rng.choice(DOMAINS_URL).format(s=slug)
    if rng.random() < 0.5:
        url = "https://" + url
    phone = f"+7 9{rng.randint(10, 99)} {rng.randint(100, 999)}-{rng.randint(10, 99)}-{rng.randint(10, 99)}"
    handle = rng.choice(["dohod", "money", "bonus", "work", "invest", "promo"]) + "_" + slug
    offer = rng.choice(SPAM_OFFERS).format(n=rng.choice([500, 3000, 5000, 10000, 50, 200, 1000, 300]))
    cta = rng.choice(SPAM_CTA).format(h=handle, u=url, p=phone)
    parts = [offer + rng.choice(["!", ".", "!!!", ""]), rng.choice(SPAM_HOOK), cta]
    if rng.random() < 0.3:
        parts.insert(0, rng.choice(["Привет всем!", "Хороший отзыв.", "Кто ищет подработку?", "Внимание!"]))
    text = " ".join(p for p in parts if p)
    return text.upper() if rng.random() < 0.1 else text


def generate(seed: int = 42, per_class: int = PER_CLASS) -> list[tuple[str, str]]:
    rng = random.Random(seed)
    rows: list[tuple[str, str]] = []
    makers = {"positive": lambda: _review(rng, True), "negative": lambda: _review(rng, False),
              "spam": lambda: _spam(rng)}
    for label, make in makers.items():
        seen = set(HARD[label])
        items = list(HARD[label])
        while len(items) < per_class:
            t = make()
            if t not in seen:
                seen.add(t)
                items.append(t)
        rows.extend((t, label) for t in items)
    rng.shuffle(rows)
    return rows


def main() -> None:
    rows = generate()
    with OUT.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["text", "label"])
        w.writerows(rows)
    print(f"{len(rows)} строк -> {OUT}")


